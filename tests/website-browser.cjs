/* Real Chrome acceptance. Start website_fixture.py first; no production target. */
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fixture = JSON.parse(fs.readFileSync(process.env.FIXTURE_LOG || '/tmp/service-harbor-website-fixture.log','utf8').split('\n')[0]);
const pause = ms => new Promise(resolve => setTimeout(resolve, ms));
(async()=>{
  const browser = await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
  const context = await browser.newContext({viewport:{width:1440,height:1000}});
  context.setDefaultTimeout(15000);
  let page = await context.newPage();
  const errors = [], live = [], requests = [];
  const attach = page => {
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', req => {
      requests.push(req.url());
      if (/\/api\/services\/[^/]+\/live$/.test(req.url())) live.push({url:req.url(),at:Date.now()});
    });
  };
  attach(page);
  async function api(path, body, method) {
    const response = await context.request.fetch(fixture.dashboard + path,{method:method || (body ? 'POST' : 'GET'),data:body,headers:{Origin:fixture.dashboard}});
    assert.equal(response.ok(),true,await response.text());return response.json();
  }
  const mark = message => console.log('PASS',message);
  try {
    await context.request.get(fixture.http+'/_set/200');
    await page.goto(fixture.dashboard);
    await page.locator('#login-password').fill('isolated-browser-only');
    await page.locator('#login-form button[type=submit]').click();
    await page.locator('#app-shell').waitFor({state:'visible'});
    await page.locator('a[data-nav="services"]').click();
    await page.locator('.service-card[data-service-id="svc-legacy"]').waitFor();
    let metrics = await (await context.request.get(fixture.http+'/_metrics')).json();
    assert.equal(metrics['/legacy'] || 0,0);
    const legacyBefore = await page.locator('.service-card[data-service-id="svc-legacy"]').textContent();
    assert.match(legacyBefore,/Website shortcut/);
    mark('old service without website_check stays disabled and does not connect');
    await page.locator('a[data-nav="add-service"]').click();
    await page.locator('#add-host').selectOption('external');
    await page.locator('#add-display-name').fill('Browser HTTP website');
    await page.locator('#add-open-url').fill(fixture.http+'/dynamic');
    await page.locator('#add-check-method').selectOption('tcp');
    assert.equal(await page.locator('#add-check-address').count(),0);
    assert.equal(await page.locator('#add-check-port').count(),0);
    assert.equal(await page.locator('#add-open-url').evaluate(node=>node.required),true);
    await page.locator('#add-check-method').selectOption('http');
    assert.equal(await page.locator('#add-check-address-row').count(),0);
    await page.screenshot({path:'/tmp/service-harbor-add-website.png',fullPage:true});
    const create = page.waitForResponse(response=>response.url()===fixture.dashboard+'/api/services' && response.request().method()==='POST');
    await page.locator('#add-register').click();
    const added = await (await create).json(); assert.equal(added.ok,true);const id=added.service.id;
    await page.waitForFunction(()=>document.querySelector('#add-form-feedback').textContent.includes('✓'));
    await page.locator('a[data-nav="services"]').click();
    const card=()=>page.locator(`.service-card[data-service-id="${id}"]`);
    await card().waitFor();
    assert.equal(await card().locator('.service-status-light').getAttribute('data-status'),'Running');
    await card().click();
    await page.waitForFunction(()=>document.querySelector('#status-output').textContent.includes('HTTP status: 200'));
    assert.equal(await page.locator('#drawer-actions [data-action]').count(),0);
    assert.equal(await page.locator('.drawer-tab[data-tab=logs]').isVisible(),false);
    assert.ok(await page.locator('#drawer-checked-at').getAttribute('datetime'));
    assert.match(await card().textContent(),/Last checked/);
    mark('HTTP creation, Running, check time, Status details; no controls or journal');
    await page.locator('button[data-close-drawer]').click();
    await page.locator('#live-indicator').click();
    await card().click();
    await pause(500);
    const startLive=live.length;
    await context.request.get(fixture.http+'/_set/503');
    await page.waitForFunction(()=>document.querySelector('#status-output').textContent.includes('HTTP status: 503'));
    await pause(6400);
    const liveSamples=live.slice(startLive).filter(r=>r.url.includes(id));
    assert.ok(liveSamples.length>=2,JSON.stringify(liveSamples));
    for(let i=1;i<liveSamples.length;i++) assert.ok(liveSamples[i].at-liveSamples[i-1].at>=2500);
    assert.match(await page.locator('#drawer-meta').textContent(),/Stopped/);
    mark(`Live updates selected HTTP website every ~3s (${liveSamples.length} observed checks), reflects 503`);
    await page.locator('button[data-close-drawer]').click();
    await page.locator('#live-indicator').click();
    await card().click();
    async function edit(method,url,address='',port='') {
      await page.locator('#drawer-rename').click();
      await page.locator('#rename-modal').waitFor({state:'visible'});
      assert.equal(await page.locator('#service-display-name').inputValue(),'Browser HTTP website');
      await page.locator('#service-check-method').selectOption(method);
      await page.locator('#service-open-url').fill(url);
      if(method==='tcp') {
        assert.equal(await page.locator('#service-check-address').count(),0);
        assert.equal(await page.locator('#service-check-port').count(),0);
      }
      const saved = page.waitForResponse(r=>r.url().endsWith(`/api/services/${id}/edit`) && r.request().method()==='PUT');
      await page.locator('#rename-form button[type=submit]').click();
      const savedResponse = await saved;
      assert.equal(savedResponse.status(),200);
      assert.equal(savedResponse.request().postDataJSON().open_url, url);
      await page.locator('#rename-modal').waitFor({state:'hidden'});
      const target = method === 'tcp' ? `${address}:${port}` : url;
      await page.waitForFunction(({method,target})=>{
        const text=document.querySelector('#status-output').textContent;
        return method==='disabled' ? text.includes('disabled') : text.includes(`Check: ${method.toUpperCase()}`) && text.includes(`Target: ${target}`);
      },{method,target});
    }
    await edit('tcp',`http://127.0.0.1:${fixture.tcp_port}`,'127.0.0.1',String(fixture.tcp_port));
    await page.waitForFunction(()=>document.querySelector('#status-output').textContent.includes('Check: TCP'));
    assert.match(await page.locator('#status-output').textContent(),/Status: Running/);
    mark('edit HTTP → URL-derived TCP, retained name and settings, Running despite HTTP 503');
    await edit('http',fixture.https+'/status/200');
    await page.waitForFunction(()=>document.querySelector('#status-output').textContent.includes('HTTP status: 200'));
    mark('HTTPS with trusted temporary CA and correct hostname is Running');
    await edit('http',fixture.bad_https+'/status/200');
    await page.waitForFunction(()=>document.querySelector('#status-output').textContent.includes('CERTIFICATE_VERIFY_FAILED'));
    assert.match(await page.locator('#drawer-meta').textContent(),/Stopped/);
    mark('HTTPS hostname mismatch is Stopped with certificate error');
    await context.request.get(fixture.http+'/_set/200');
    await edit('http',fixture.http+'/dynamic');
    await page.waitForFunction(()=>document.querySelector('#status-output').textContent.includes('HTTP status: 200'));
    const bells=page.locator('#detail-drawer .tracking-bell');
    await bells.click();
    await page.locator('#detail-drawer .tracking-menu button').filter({hasText:'5 minutes'}).click();
    const deadline=await page.evaluate(()=>JSON.parse(localStorage.getItem('host-dashboard-tracking-v1'))[0].endsAt);
    await pause(700);
    const trackStart=live.length;
    const trackingDeadline = Date.now() + 20000;
    while(live.slice(trackStart).filter(r=>r.url.includes(id)).length < 2 && Date.now() < trackingDeadline) await pause(250);
    const samples=live.slice(trackStart).filter(r=>r.url.includes(id));
    assert.ok(samples.length>=2,JSON.stringify(samples));
    for(let i=1;i<samples.length;i++) assert.ok(samples[i].at-samples[i-1].at>=4500);
    assert.equal(requests.filter(url=>url.includes(`/api/services/${id}/logs`)).length,0);
    await page.screenshot({path:'/tmp/service-harbor-website-tracking.png',fullPage:true});
    mark(`bell checks website every ~5s (${samples.length} observed checks), no log requests`);
    await page.close();
    await pause(1000);
    metrics=await (await context.request.get(fixture.http+'/_metrics')).json();
    await pause(6000);
    const afterClosed=await (await context.request.get(fixture.http+'/_metrics')).json();
    assert.equal(afterClosed['/dynamic'],metrics['/dynamic']);
    const reopenStart = live.length;
    page=await context.newPage(); attach(page);
    await page.goto(fixture.dashboard+'/#services');
    await card().waitFor();
    await pause(1500);
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('host-dashboard-tracking-v1'))[0].endsAt),deadline);
    assert.ok(live.slice(reopenStart).some(r=>r.url.includes(id)));
    mark('closing page stops probes; reopening preserves absolute tracking deadline');
    await card().click();
    await page.locator('#detail-drawer .tracking-bell').click();
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('host-dashboard-tracking-v1')).length),0);
    await pause(1000);
    const stopped=live.length; await pause(6000); assert.equal(live.length,stopped);
    mark('click active bell stops tracking');
    await edit('disabled',fixture.http+'/disabled');
    await page.waitForFunction(()=>document.querySelector('#status-output').textContent.includes('disabled'));
    await pause(1000);
    metrics=await (await context.request.get(fixture.http+'/_metrics')).json();
    assert.equal(metrics['/disabled']||0,0);
    mark('editing to Disabled stops network checks');
    const exported=await api('/api/services/export?selection=service&value='+id);
    assert.deepEqual(exported.services[0].website_check,{method:'disabled'});
    await page.locator('button[data-close-drawer]').click();
    await page.locator('#detail-drawer').waitFor({state:'hidden'});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:'/tmp/service-harbor-website-mobile.png',fullPage:true});
    const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,viewport:innerWidth}));
    assert.ok(width.scroll<=width.viewport,JSON.stringify(width));
    assert.deepEqual(errors,[]);
    mark('mobile Services has no horizontal overflow; no uncaught browser errors');
    console.log(JSON.stringify({result:'PASS',service_id:id,browser_errors:errors,live_intervals_ms:liveSamples.slice(1).map((v,i)=>v.at-liveSamples[i].at),tracking_intervals_ms:samples.slice(1).map((v,i)=>v.at-samples[i].at)},null,2));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
